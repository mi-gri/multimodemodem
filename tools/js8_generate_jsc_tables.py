"""Convert the JSC word tables of JS8Call 2.2.0 (jsc_map.cpp, jsc_list.cpp)
into the compact text resource third_party/js8call_gpl/jsc_tables.txt.

The C++ originals are 12 MB of initialisers; the resource keeps exactly the
same data (word, size field, ordering) and is loaded once at runtime.

Usage: js8_generate_jsc_tables.py <js8call/src> <output file>
"""
import re
import sys

ENTRY = re.compile(rb'^\s*\{("(?:[^"\\]|\\.)*")(?:\s*/\*.*?\*/)?\s*,\s*(\d+)\s*,\s*(\d+)\s*\},?\s*(?://.*)?$')


def c_string(literal: bytes) -> bytes:
    body = literal[1:-1]
    out = bytearray()
    i = 0
    while i < len(body):
        c = body[i]
        if c == 0x5C:  # backslash
            n = body[i + 1]
            if n == ord('x'):
                j = i + 2
                while j < len(body) and j < i + 4 and chr(body[j]) in '0123456789abcdefABCDEF':
                    j += 1
                out.append(int(body[i + 2:j], 16))
                i = j
                continue
            out.append({ord('n'): 10, ord('t'): 9, ord('\\'): 92, ord('"'): 34, ord("'"): 39}[n])
            i += 2
            continue
        out.append(c)
        i += 1
    return bytes(out)


def parse(path, table):
    entries = []
    active = False
    with open(path, 'rb') as f:
        for line in f:
            if line.startswith(b'const Tuple JSC::'):
                active = (b'JSC::' + table.encode() + b'[') in line
                continue
            if not active:
                continue
            if line.startswith(b'};'):
                active = False
                continue
            m = ENTRY.match(line.rstrip(b'\r\n'))
            if m:
                entries.append((c_string(m.group(1)), int(m.group(2)), int(m.group(3))))
    return entries


def escape(word: bytes) -> str:
    return ''.join(chr(b) if 0x20 <= b < 0x7F and b not in (0x5C, 0x09) else '\\x%02x' % b for b in word)


def main():
    src, out = sys.argv[1], sys.argv[2]
    mp = parse(src + '/jsc_map.cpp', 'map')
    lst = parse(src + '/jsc_list.cpp', 'list')
    prefix = parse(src + '/jsc_list.cpp', 'prefix')
    assert len(mp) == 262144 and len(lst) == 262144 and len(prefix) == 103, (len(mp), len(lst), len(prefix))
    for i, (_, _, index) in enumerate(mp):
        assert index == i, (i, index)
    for word, size, index in lst:
        assert mp[index][0] == word, (word, size, index)
    with open(out, 'w', encoding='ascii', newline='\n') as f:
        f.write('# JSC tables of JS8Call 2.2.0 (C) 2018 Jordan Sherer KN4CRD, GPL-3.0-or-later.\n')
        f.write('# Generated by tools/js8_generate_jsc_tables.py; do not edit.\n')
        f.write('MAP %d\n' % len(mp))
        for word, size, _ in mp:
            f.write('%s\t%d\n' % (escape(word), size))
        f.write('LIST %d\n' % len(lst))
        for k in range(0, len(lst), 16):
            # "index" when the list entry repeats the map size, else "index:size"
            # (JS8Call's ROSIDS entry differs between the two tables).
            f.write(' '.join(str(e[2]) if mp[e[2]][1] == e[1] else '%d:%d' % (e[2], e[1])
                             for e in lst[k:k + 16]) + '\n')
        f.write('PREFIX %d\n' % len(prefix))
        for word, size, index in prefix:
            f.write('%s\t%d\t%d\n' % (escape(word), size, index))


if __name__ == '__main__':
    main()
